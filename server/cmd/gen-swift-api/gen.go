type declKind int

const (
	kindStruct declKind = iota
	kindEnum
	kindAlias
)

type decl struct {
	name   string
	doc    string
	kind   declKind
	alias  string   // kindAlias: the aliased type
	fields []*field // kindStruct
	cases  []string // kindEnum: raw values
	nested []*decl
	used   map[string]bool // nested type names taken in this struct
}

type field struct {
	json, swift, typ   string
	required, nullable bool
	collection         string // "[]" or "[:]" for arrays and maps, which decode null as empty
	doc                string
}

type param struct {
	name, label, typ, in string
	required             bool
}

type operation struct {
	name, method, template, summary, doc string
	params                               []param
	bodyType, bodyKind                   string // bodyKind: json, multipart, raw
	bodyContentType                      string
	bodyRequired                         bool
	response, decode                     string
}

type gen struct {
	doc         *openapi3.T
	top         map[string]bool   // every top-level Swift name in API
	schemaNames map[string]string // component schema name -> Swift name
	decls       []*decl
	ops         []*operation
}

func (g *gen) collect() error {
	names := make([]string, 0, len(g.doc.Components.Schemas))
	for name := range g.doc.Components.Schemas {
		names = append(names, name)
	}
	sort.Strings(names)
	// Register every component name first, so nested types never shadow one.
	for _, name := range names {
		swift := g.uniqueTop(pascal(name))
		g.schemaNames[name] = swift
	}
	for _, name := range names {
		ref := g.doc.Components.Schemas[name]
		if ref.Value == nil {
			return fmt.Errorf("schema %s has no value", name)
		}
		g.decls = append(g.decls, g.topDecl(g.schemaNames[name], ref.Value))
	}
	return g.collectOperations()
}

// uniqueTop reserves a top-level name, adding a suffix when it's taken.
func (g *gen) uniqueTop(base string) string {
	name := base
	if reservedTypeNames[name] {
		name += "Value"
	}
	for i := 2; g.top[name]; i++ {
		name = fmt.Sprintf("%s%d", base, i)
	}
	g.top[name] = true
	return name
}

// nestedName reserves a nested type name inside d, never shadowing a top-level name.
func (g *gen) nestedName(d *decl, base string) string {
	if d == nil {
		return g.uniqueTop(base)
	}
	if d.used == nil {
		d.used = map[string]bool{}
	}
	name := base
	if g.top[name] || reservedTypeNames[name] || name == d.name {
		name = base + "Value"
	}
	for i := 2; g.top[name] || d.used[name] || name == d.name; i++ {
		name = fmt.Sprintf("%sValue%d", base, i)
	}
	d.used[name] = true
	return name
}

func (g *gen) topDecl(name string, s *openapi3.Schema) *decl {
	switch {
	case isStringEnum(s):
		return enumDecl(name, s)
	case isObject(s):
		d := &decl{name: name, doc: s.Description, kind: kindStruct}
		g.fillStruct(d, s)
		return d
	default:
		d := &decl{name: name, doc: s.Description, kind: kindAlias}
		// An alias can't hold nested types, so an inline element type becomes a top-level one.
		d.alias = g.typeFor(&openapi3.SchemaRef{Value: s}, name+"Item", nil)
		return d
	}
}

func enumDecl(name string, s *openapi3.Schema) *decl {
	d := &decl{name: name, doc: s.Description, kind: kindEnum}
	for _, v := range s.Enum {
		if str, ok := v.(string); ok {
			d.cases = append(d.cases, str)
		}
	}
	return d
}

func isStringEnum(s *openapi3.Schema) bool {
	return len(s.Enum) > 0 && (s.Type == nil || s.Type.Is("string") || s.Type.IsEmpty())
}

func isObject(s *openapi3.Schema) bool {
	return len(s.Properties) > 0 || len(s.AllOf) > 1
}

// fillStruct adds the properties of s, and of every allOf part, to d.
func (g *gen) fillStruct(d *decl, s *openapi3.Schema) {
	props := map[string]*openapi3.SchemaRef{}
	required := map[string]bool{}
	var merge func(s *openapi3.Schema)
	merge = func(s *openapi3.Schema) {
		for _, part := range s.AllOf {
			if part.Value != nil {
				merge(part.Value)
			}
		}
		for name, p := range s.Properties {
			props[name] = p
		}
		for _, r := range s.Required {
			required[r] = true
		}
	}
	merge(s)

	jsonNames := make([]string, 0, len(props))
	for name := range props {
		jsonNames = append(jsonNames, name)
	}
	sort.Strings(jsonNames)
	taken := map[string]bool{}
	for _, jn := range jsonNames {
		p := props[jn]
		f := &field{json: jn, required: required[jn]}
		f.swift = camel(jn)
		for i := 2; taken[f.swift]; i++ {
			f.swift = fmt.Sprintf("%s%d", camel(jn), i)
		}
		taken[f.swift] = true
		if p.Value != nil {
			f.nullable = p.Value.Nullable
			f.doc = p.Value.Description
		}
		f.typ = g.typeFor(p, pascal(jn), d)
		f.collection = emptyLiteral(f.typ)
		d.fields = append(d.fields, f)
	}
}

// typeFor returns the Swift type for a schema, adding any inline object or enum as a nested type of
// owner (or as a top-level type when owner is nil) named after hint.
func (g *gen) typeFor(ref *openapi3.SchemaRef, hint string, owner *decl) string {
	if ref == nil || ref.Value == nil {
		return "JSONValue"
	}
	if name, ok := strings.CutPrefix(ref.Ref, "#/components/schemas/"); ok {
		if swift, ok := g.schemaNames[name]; ok {
			return swift
		}
	}
	s := ref.Value
	// `allOf: [$ref]` beside `nullable: true` is how the spec makes a reference nullable.
	if len(s.AllOf) == 1 && len(s.Properties) == 0 {
		return g.typeFor(s.AllOf[0], hint, owner)
	}
	if isStringEnum(s) {
		d := enumDecl(g.nestedName(owner, hint), s)
		g.attach(owner, d)
		return d.name
	}
	if len(s.Properties) > 0 || len(s.AllOf) > 1 {
		d := &decl{name: g.nestedName(owner, hint), doc: s.Description, kind: kindStruct}
		g.attach(owner, d)
		g.fillStruct(d, s)
		return d.name
	}
	switch {
	case s.Type == nil || s.Type.IsEmpty():
		if s.Items != nil {
			return "[" + g.typeFor(s.Items, hint+"Item", owner) + "]"
		}
		return "JSONValue"
	case s.Type.Is("string"):
		if s.Format == "binary" {
			return "Foundation.Data"
		}
		return "Swift.String"
	case s.Type.Is("integer"):
		return "Swift.Int"
	case s.Type.Is("number"):
		return "Swift.Double"
	case s.Type.Is("boolean"):
		return "Swift.Bool"
	case s.Type.Is("array"):
		return "[" + g.typeFor(s.Items, hint+"Item", owner) + "]"
	case s.Type.Is("object"):
		if ap := s.AdditionalProperties.Schema; ap != nil {
			return "[Swift.String: " + g.typeFor(ap, hint+"Value", owner) + "]"
		}
		if has := s.AdditionalProperties.Has; has != nil && *has {
			return "[Swift.String: JSONValue]"
		}
		return "JSONValue"
	}
	return "JSONValue"
}

// emptyLiteral is "[]" for an array type, "[:]" for a dictionary type and "" otherwise, judged by
// the outermost brackets so `[[String: X]]` is an array.
func emptyLiteral(typ string) string {
	if !strings.HasPrefix(typ, "[") {
		return ""
	}
	depth := 0
	for _, r := range typ {
		switch r {
		case '[':
			depth++
		case ']':
			depth--
		case ':':
			if depth == 1 {
				return "[:]"
			}
		}
	}
	return "[]"
}

func (g *gen) attach(owner *decl, d *decl) {
	if owner == nil {
		g.decls = append(g.decls, d)
		return
	}
	owner.nested = append(owner.nested, d)
}

var methodOrder = []string{"GET", "PUT", "POST", "PATCH", "DELETE", "HEAD", "OPTIONS"}

func (g *gen) collectOperations() error {
	paths := g.doc.Paths.Map()
	templates := make([]string, 0, len(paths))
	for t := range paths {
		templates = append(templates, t)
	}
	sort.Strings(templates)
	usedNames := map[string]bool{}
	for _, tmpl := range templates {
		item := paths[tmpl]
		opsByMethod := item.Operations()
		for _, method := range methodOrder {
			op := opsByMethod[method]
			if op == nil {
				continue
			}
			if op.OperationID == "" {
				return fmt.Errorf("%s %s has no operationId", method, tmpl)
			}
			o := &operation{method: method, template: tmpl, summary: op.Summary, doc: op.Description}
			o.name = camel(op.OperationID)
			for i := 2; usedNames[o.name]; i++ {
				o.name = fmt.Sprintf("%s%d", camel(op.OperationID), i)
			}
			usedNames[o.name] = true
			opPascal := pascal(op.OperationID)

			labels := map[string]bool{}
			label := func(base string) string {
				l := base
				for i := 2; labels[l]; i++ {
					l = fmt.Sprintf("%s%d", base, i)
				}
				labels[l] = true
				return l
			}
			for _, p := range mergeParams(item.Parameters, op.Parameters) {
				if p.In == "cookie" {
					continue
				}
				typ := g.typeFor(p.Schema, opPascal+pascal(p.Name), nil)
				o.params = append(o.params, param{
					name: p.Name, label: label(camel(p.Name)), typ: typ, in: p.In,
					required: p.Required || p.In == "path",
				})
			}
			if rb := op.RequestBody; rb != nil && rb.Value != nil {
				o.bodyRequired = rb.Value.Required
				switch {
				case rb.Value.Content.Get("application/json") != nil:
					o.bodyKind = "json"
					o.bodyType = g.typeFor(rb.Value.Content.Get("application/json").Schema, opPascal+"Body", nil)
				case rb.Value.Content.Get("multipart/form-data") != nil:
					o.bodyKind = "multipart"
					o.bodyType = "APIMultipartForm"
				default:
					o.bodyKind = "raw"
					o.bodyType = "Foundation.Data"
					cts := make([]string, 0, len(rb.Value.Content))
					for ct := range rb.Value.Content {
						cts = append(cts, ct)
					}
					sort.Strings(cts)
					if len(cts) > 0 {
						o.bodyContentType = cts[0]
					}
				}
			}
			o.response, o.decode = g.responseType(op, opPascal)
			o.params = orderParams(o)
			g.ops = append(g.ops, o)
		}
	}
	return nil
}

func mergeParams(pathLevel, opLevel openapi3.Parameters) []*openapi3.Parameter {
	var out []*openapi3.Parameter
	index := map[string]int{}
	for _, list := range []openapi3.Parameters{pathLevel, opLevel} {
		for _, ref := range list {
			if ref == nil || ref.Value == nil {
				continue
			}
			key := ref.Value.In + ":" + ref.Value.Name
			if i, ok := index[key]; ok {
				out[i] = ref.Value
				continue
			}
			index[key] = len(out)
			out = append(out, ref.Value)
		}
	}
	return out
}

// orderParams puts path parameters first (in template order), then required query parameters,
// a required body, and everything optional last, so call sites read like the URL.
func orderParams(o *operation) []param {
	var path, req, opt []param
	for _, p := range o.params {
		switch {
		case p.in == "path":
			path = append(path, p)
		case p.required:
			req = append(req, p)
		default:
			opt = append(opt, p)
		}
	}
	sort.SliceStable(path, func(i, j int) bool {
		return strings.Index(o.template, "{"+path[i].name+"}") < strings.Index(o.template, "{"+path[j].name+"}")
	})
	return append(append(path, req...), opt...)
}

func (g *gen) responseType(op *openapi3.Operation, opPascal string) (typ, decode string) {
	if op.Responses == nil {
		return "APIEmpty", ".empty"
	}
	codes := []string{}
	for code := range op.Responses.Map() {
		if len(code) == 3 && code[0] == '2' {
			codes = append(codes, code)
		}
	}
	sort.Strings(codes)
	if len(codes) == 0 {
		return "APIEmpty", ".empty"
	}
	resp := op.Responses.Map()[codes[0]]
	if resp == nil || resp.Value == nil || len(resp.Value.Content) == 0 {
		return "APIEmpty", ".empty"
	}
	if mt := resp.Value.Content.Get("application/json"); mt != nil {
		return g.typeFor(mt.Schema, opPascal+"Response", nil), ".json"
	}
	return "Foundation.Data", ".raw"
}

// MARK: Writing Swift

func writeDoc(b *bytes.Buffer, doc, indent string) {
	doc = strings.TrimSpace(doc)
	if doc == "" {
		return
	}
	for _, line := range strings.Split(doc, "\n") {
		line = strings.TrimRight(line, " \t")
		if line == "" {
			b.WriteString(indent + "///\n")
			continue
		}
		b.WriteString(indent + "/// " + line + "\n")
	}
}

func writeDecl(b *bytes.Buffer, d *decl, indent string) {
	writeDoc(b, d.doc, indent)
	switch d.kind {
	case kindAlias:
		fmt.Fprintf(b, "%spublic typealias %s = %s\n", indent, d.name, d.alias)
	case kindEnum:
		writeEnum(b, d, indent)
	case kindStruct:
		writeStruct(b, d, indent)
	}
}

func writeEnum(b *bytes.Buffer, d *decl, indent string) {
	in := indent + "    "
	fmt.Fprintf(b, "%spublic struct %s: APIStringEnum {\n", indent, d.name)
	fmt.Fprintf(b, "%spublic let rawValue: Swift.String\n", in)
	fmt.Fprintf(b, "%spublic init(rawValue: Swift.String) { self.rawValue = rawValue }\n", in)
	taken := map[string]bool{"rawValue": true, "allKnown": true, "description": true, "init": true}
	var names []string
	for _, v := range d.cases {
		base := camel(v)
		if base == "" || base == "_" {
			base = "empty"
		}
		name := base
		for i := 2; taken[name]; i++ {
			name = fmt.Sprintf("%s%d", base, i)
		}
		taken[name] = true
		names = append(names, name)
		fmt.Fprintf(b, "%spublic static let %s = %s(rawValue: %s)\n", in, ident(name), d.name, swiftString(v))
	}
	quoted := make([]string, len(names))
	for i, n := range names {
		quoted[i] = ident(n)
	}
	fmt.Fprintf(b, "%spublic static let allKnown: [%s] = [%s]\n", in, d.name, strings.Join(quoted, ", "))
	fmt.Fprintf(b, "%s}\n", indent)
}

func (f *field) declType() string {
	switch {
	case f.required && !f.nullable:
		return f.typ
	case !f.required && f.nullable:
		return "APINullable<" + f.typ + ">?"
	default:
		return f.typ + "?"
	}
}

func writeStruct(b *bytes.Buffer, d *decl, indent string) {
	in := indent + "    "
	fmt.Fprintf(b, "%spublic struct %s: Codable, Sendable, Equatable {\n", indent, d.name)
	for _, f := range d.fields {
		writeDoc(b, f.doc, in)
		fmt.Fprintf(b, "%spublic var %s: %s\n", in, ident(f.swift), f.declType())
	}
	for _, n := range d.nested {
		b.WriteString("\n")
		writeDecl(b, n, in)
	}
	if len(d.fields) == 0 {
		fmt.Fprintf(b, "\n%spublic init() {}\n", in)
		fmt.Fprintf(b, "%s}\n", indent)
		return
	}

	// Memberwise init: optional members default to nil.
	b.WriteString("\n")
	args := make([]string, len(d.fields))
	for i, f := range d.fields {
		arg := ident(f.swift) + ": " + f.declType()
		if strings.HasSuffix(f.declType(), "?") {
			arg += " = nil"
		}
		args[i] = arg
	}
	fmt.Fprintf(b, "%spublic init(\n%s    %s\n%s) {\n", in, in, strings.Join(args, ",\n"+in+"    "), in)
	for _, f := range d.fields {
		fmt.Fprintf(b, "%s    self.%s = %s\n", in, ident(f.swift), ident(f.swift))
	}
	fmt.Fprintf(b, "%s}\n", in)

	b.WriteString("\n")
	fmt.Fprintf(b, "%senum CodingKeys: Swift.String, CodingKey {\n", in)
	for _, f := range d.fields {
		if f.swift == f.json {
			fmt.Fprintf(b, "%s    case %s\n", in, ident(f.swift))
		} else {
			fmt.Fprintf(b, "%s    case %s = %s\n", in, ident(f.swift), swiftString(f.json))
		}
	}
	fmt.Fprintf(b, "%s}\n", in)

	// Decoding: Go encodes a nil slice or map as null, so a required collection decodes null or a
	// missing key as empty rather than failing the whole response.
	b.WriteString("\n")
	fmt.Fprintf(b, "%spublic init(from decoder: any Decoder) throws {\n", in)
	fmt.Fprintf(b, "%s    let c = try decoder.container(keyedBy: CodingKeys.self)\n", in)
	for _, f := range d.fields {
		key := "." + ident(f.swift)
		var expr string
		switch {
		case f.required && !f.nullable && f.collection != "":
			expr = fmt.Sprintf("try c.decodeIfPresent(%s.self, forKey: %s) ?? %s", f.typ, key, f.collection)
		case f.required && !f.nullable:
			expr = fmt.Sprintf("try c.decode(%s.self, forKey: %s)", f.typ, key)
		case !f.required && f.nullable:
			expr = fmt.Sprintf("try c.decodeNullable(%s.self, forKey: %s)", f.typ, key)
		default:
			expr = fmt.Sprintf("try c.decodeIfPresent(%s.self, forKey: %s)", f.typ, key)
		}
		fmt.Fprintf(b, "%s    self.%s = %s\n", in, ident(f.swift), expr)
	}
	fmt.Fprintf(b, "%s}\n", in)

	// Encoding: optional members are left out when nil; a required nullable one is sent as null.
	b.WriteString("\n")
	fmt.Fprintf(b, "%spublic func encode(to encoder: any Encoder) throws {\n", in)
	fmt.Fprintf(b, "%s    var c = encoder.container(keyedBy: CodingKeys.self)\n", in)
	for _, f := range d.fields {
		fn := "encodeIfPresent"
		if f.required {
			fn = "encode"
		}
		fmt.Fprintf(b, "%s    try c.%s(%s, forKey: .%s)\n", in, fn, ident(f.swift), ident(f.swift))
	}
	fmt.Fprintf(b, "%s}\n", in)
	fmt.Fprintf(b, "%s}\n", indent)
}

func writeOperation(b *bytes.Buffer, o *operation, indent string) {
	in := indent + "    "
	doc := strings.TrimSpace(o.summary)
	if d := strings.TrimSpace(o.doc); d != "" {
		if doc != "" {
			doc += "\n\n"
		}
		doc += d
	}
	if doc != "" {
		doc += "\n\n"
	}
	doc += "`" + o.method + " " + o.template + "`"
	writeDoc(b, doc, indent)

	var args []string
	bodyLabel := ""
	labels := map[string]bool{}
	for _, p := range o.params {
		labels[p.label] = true
	}
	if o.bodyKind != "" {
		bodyLabel = "body"
		for i := 2; labels[bodyLabel]; i++ {
			bodyLabel = fmt.Sprintf("body%d", i)
		}
	}
	addBody := func() {
		if o.bodyRequired {
			args = append(args, bodyLabel+": "+o.bodyType)
		} else {
			args = append(args, bodyLabel+": "+o.bodyType+"? = nil")
		}
	}
	bodyAdded := o.bodyKind == ""
	for _, p := range o.params {
		if !p.required && !bodyAdded && o.bodyRequired {
			addBody()
			bodyAdded = true
		}
		if p.required {
			args = append(args, ident(p.label)+": "+p.typ)
		} else {
			args = append(args, ident(p.label)+": "+p.typ+"? = nil")
		}
	}
	if !bodyAdded {
		addBody()
	}

	fmt.Fprintf(b, "%spublic static func %s(%s) -> APIRequest<%s> {\n", indent, ident(o.name), strings.Join(args, ", "), o.response)

	path := "/api/v1" + o.template
	for _, p := range o.params {
		if p.in == "path" {
			path = strings.ReplaceAll(path, "{"+p.name+"}", `\(APIPath.escape(`+ident(p.label)+`))`)
		}
	}
	hasQuery, hasHeaders := false, false
	for _, p := range o.params {
		hasQuery = hasQuery || p.in == "query"
		hasHeaders = hasHeaders || p.in == "header"
	}
	queryArg, headersArg := "[]", "[:]"
	if hasQuery {
		fmt.Fprintf(b, "%svar _query: [URLQueryItem] = []\n", in)
		for _, p := range o.params {
			if p.in == "query" {
				fmt.Fprintf(b, "%sAPIQuery.append(&_query, %s, %s)\n", in, swiftString(p.name), ident(p.label))
			}
		}
		queryArg = "_query"
	}
	if hasHeaders {
		fmt.Fprintf(b, "%svar _headers: [Swift.String: Swift.String] = [:]\n", in)
		for _, p := range o.params {
			if p.in == "header" {
				fmt.Fprintf(b, "%sAPIQuery.set(&_headers, %s, %s)\n", in, swiftString(p.name), ident(p.label))
			}
		}
		headersArg = "_headers"
	}
	bodyArg := "nil"
	switch o.bodyKind {
	case "json":
		if o.bodyRequired {
			bodyArg = "APIRequestBody.json(" + bodyLabel + ")"
		} else {
			bodyArg = bodyLabel + ".map { APIRequestBody.json($0) }"
		}
	case "multipart":
		if o.bodyRequired {
			bodyArg = "APIRequestBody.multipart(" + bodyLabel + ")"
		} else {
			bodyArg = bodyLabel + ".map { APIRequestBody.multipart($0) }"
		}
	case "raw":
		if o.bodyRequired {
			bodyArg = "APIRequestBody.raw(" + bodyLabel + ", contentType: " + swiftString(o.bodyContentType) + ")"
		} else {
			bodyArg = bodyLabel + ".map { APIRequestBody.raw($0, contentType: " + swiftString(o.bodyContentType) + ") }"
		}
	}
	fmt.Fprintf(b, "%sreturn APIRequest(\n", in)
	fmt.Fprintf(b, "%s    method: %s, template: %s,\n", in, swiftString(o.method), swiftString(o.template))
	fmt.Fprintf(b, "%s    path: \"%s\",\n", in, path)
	fmt.Fprintf(b, "%s    query: %s, headers: %s, body: %s, decode: %s\n", in, queryArg, headersArg, bodyArg, o.decode)
	fmt.Fprintf(b, "%s)\n", in)
	fmt.Fprintf(b, "%s}\n", indent)
}

// MARK: Names

func words(s string) []string {
	var out []string
	var cur []rune
	flush := func() {
		if len(cur) > 0 {
			out = append(out, string(cur))
			cur = nil
		}
	}
	runes := []rune(s)
	for i, r := range runes {
		switch {
		case !unicode.IsLetter(r) && !unicode.IsDigit(r):
			flush()
		case unicode.IsUpper(r) && len(cur) > 0 &&
			(unicode.IsLower(cur[len(cur)-1]) || unicode.IsDigit(cur[len(cur)-1]) ||
				(i+1 < len(runes) && unicode.IsLower(runes[i+1]))):
			flush()
			cur = append(cur, r)
		default:
			cur = append(cur, r)
		}
	}
	flush()
	return out
}

func capitalize(w string) string {
	r := []rune(w)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}

func pascal(s string) string {
	var b strings.Builder
	for _, w := range words(s) {
		b.WriteString(capitalize(w))
	}
	name := b.String()
	if name == "" {
		return "Value"
	}
	if unicode.IsDigit([]rune(name)[0]) {
		name = "V" + name
	}
	return name
}

func camel(s string) string {
	ws := words(s)
	if len(ws) == 0 {
		return "_"
	}
	var b strings.Builder
	first := ws[0]
	if strings.ToUpper(first) == first {
		first = strings.ToLower(first)
	} else {
		r := []rune(first)
		r[0] = unicode.ToLower(r[0])
		first = string(r)
	}
	b.WriteString(first)
	for _, w := range ws[1:] {
		b.WriteString(capitalize(w))
	}
	name := b.String()
	if unicode.IsDigit([]rune(name)[0]) {
		name = "_" + name
	}
	return name
}

// ident escapes a Swift keyword with backticks.
func ident(name string) string {
	if swiftKeywords[name] {
		return "`" + name + "`"
	}
	return name
}

func swiftString(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`, "\r", `\r`, "\t", `\t`)
	return `"` + r.Replace(s) + `"`
}
