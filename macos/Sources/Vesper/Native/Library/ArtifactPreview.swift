/// A labelled field in a sheet (the web's <Field>), with an optional hint under it.
private struct SheetField<Content: View>: View {
    @Environment(\.vesperTheme) private var theme
    let label: String
    var hint: String?
    @ViewBuilder let content: Content

    var body: some View {
        VStack(alignment: .leading, spacing: 4) {
            Text(label).font(.system(size: theme.pointSize(.small), weight: .medium)).foregroundStyle(theme.palette.secondaryText)
            content
            if let hint { Text(hint).font(.system(size: theme.pointSize(.small))).foregroundStyle(theme.palette.tertiaryText) }
        }
    }
}

/// Space and Epic pickers, shared by Upload and New mockup.
private struct SpaceEpicPickers: View {
    @Environment(NativeScreenContext.self) private var context
    @Binding var projectKey: String
    @Binding var epicId: String

    private static let bootstrap = API.getBootstrap()

    var body: some View {
        let boot = context.store.entry(Self.bootstrap).data
        let projects = (boot?.projects ?? []).filter { !$0.archived }
        let project = projects.first { $0.key == projectKey } ?? projects.first
        let epics = (boot?.epics ?? []).filter { $0.projectId == project?.id }
        HStack(alignment: .top, spacing: 12) {
            SheetField(label: "Space") {
                Picker("Space", selection: Binding(get: { project?.key ?? "" }, set: { projectKey = $0; epicId = "" })) {
                    ForEach(projects, id: \.key) { Text($0.name).tag($0.key) }
                }
                .labelsHidden()
            }
            SheetField(label: "Epic") {
                Picker("Epic", selection: $epicId) {
                    Text("No epic").tag("")
                    ForEach(epics, id: \.id) { Text($0.name).tag($0.id) }
                }
                .labelsHidden()
            }
        }
        .task { context.store.load(Self.bootstrap) }
        .onChange(of: projects.map(\.key), initial: true) { _, keys in
            if !keys.contains(projectKey), let first = keys.first { projectKey = first }
        }
    }
}

/// The picked files, each removable, with a button to pick more (the web's FilePicker).
private struct FileList: View {
    @Environment(\.vesperTheme) private var theme
    @Binding var files: [URL]
    var multiple = true
    var types: [UTType]?
    var hint: String?
    var onPick: ([URL]) -> Void = { _ in }

    var body: some View {
        VStack(alignment: .leading, spacing: 6) {
            ForEach(files, id: \.self) { file in
                HStack {
                    Image(systemName: "doc")
                    Text(file.lastPathComponent).lineLimit(1)
                    Spacer()
                    Text(LibraryLogic.formatBytes((try? file.resourceValues(forKeys: [.fileSizeKey]).fileSize) ?? 0))
                        .foregroundStyle(theme.palette.tertiaryText)
                    Button { files.removeAll { $0 == file } } label: { Image(systemName: "xmark") }
                        .buttonStyle(.plain).accessibilityLabel("Remove \(file.lastPathComponent)")
                }
                .font(.system(size: theme.pointSize(.small)))
            }
            Button(files.isEmpty ? "Choose \(multiple ? "files" : "a file")\u{2026}" : "Choose other\u{2026}") { pick() }.buttonStyle(.vesper())
            if let hint { Text(hint).font(.system(size: theme.pointSize(.small))).foregroundStyle(theme.palette.tertiaryText) }
        }
        .padding(12)
        .frame(maxWidth: .infinity, alignment: .leading)
        .overlay(RoundedRectangle(cornerRadius: 8).strokeBorder(theme.swiftUIColor("border-strong", fallback: theme.palette.border), style: StrokeStyle(lineWidth: 1, dash: [4, 3])))
        .onDrop(of: [.fileURL], isTargeted: nil) { providers in
            Task {
                var dropped: [URL] = []
                for provider in providers {
                    if let data = try? await provider.loadItem(forTypeIdentifier: UTType.fileURL.identifier) as? Data,
                       let url = URL(dataRepresentation: data, relativeTo: nil) { dropped.append(url) }
                }
                if !dropped.isEmpty { take(dropped) }
            }
            return true
        }
    }

    private func pick() {
        let panel = NSOpenPanel()
        panel.allowsMultipleSelection = multiple
        panel.canChooseDirectories = false
        if let types { panel.allowedContentTypes = types }
        guard panel.runModal() == .OK else { return }
        take(panel.urls)
    }

    private func take(_ urls: [URL]) {
        files = multiple ? urls : Array(urls.prefix(1))
        onPick(files)
    }
}

/// A sheet's frame: title, body and a footer with the error and buttons (the web's DialogShell).
private struct SheetShell<Content: View, Footer: View>: View {
    @Environment(\.vesperTheme) private var theme
    let title: String
    @ViewBuilder let content: Content
    @ViewBuilder let footer: Footer

    var body: some View {
        VStack(alignment: .leading, spacing: 16) {
            Text(title).vesperText(.heading, theme)
            content
            HStack(spacing: 8) { footer }
        }
        .padding(20)
        .frame(width: 560)
        .vesperText(.body, theme)
        .background(theme.swiftUIColor("surface-raised", fallback: theme.palette.surface))
        .foregroundStyle(theme.palette.text)
    }
}

private func mimeType(_ url: URL) -> String {
    UTType(filenameExtension: url.pathExtension)?.preferredMIMEType ?? "application/octet-stream"
}

/// Add artifact: upload files or write markdown, with its type, space, epic and title.
struct ArtifactUploadSheet: View {
    @Environment(NativeScreenContext.self) private var context
    @Environment(\.vesperTheme) private var theme
    @Environment(\.dismiss) private var dismiss
    let initialFiles: [URL]
    let defaultProject: String
    let created: (API.Artifact) -> Void

    @State private var write = false
    @State private var files: [URL] = []
    @State private var body_ = ""
    @State private var type = API.ArtifactType.spec
    @State private var projectKey = ""
    @State private var epicId = ""
    @State private var title = ""
    @State private var progress: String?
    @State private var error: String?
    @State private var busy = false

    var body: some View {
        let ready = !projectKey.isEmpty && (write ? !body_.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty : !files.isEmpty)
        SheetShell(title: "Add artifact") {
            Picker("Source", selection: $write) {
                Text("Upload").tag(false)
                Text("Write markdown").tag(true)
            }
            .pickerStyle(.segmented)
            .labelsHidden()
            .fixedSize()
            if write {
                SheetField(label: "Markdown", hint: "Headings become the outline agents cite. The first # heading is the title unless you set one.") {
                    TextEditor(text: $body_)
                        .font(.system(size: theme.pointSize(.mono), design: .monospaced))
                        .frame(height: 200)
                        .overlay(RoundedRectangle(cornerRadius: 6).stroke(theme.palette.border))
                }
            } else {
                FileList(files: $files) { picked in
                    if let first = picked.first { type = LibraryLogic.guessType(name: first.lastPathComponent, mime: mimeType(first)) }
                }
            }
            HStack(alignment: .top, spacing: 12) {
                SheetField(label: "Type") {
                    Picker("Type", selection: $type) {
                        ForEach(LibraryLogic.uploadTypes.indices, id: \.self) { i in
                            Text(LibraryLogic.uploadTypes[i].label).tag(LibraryLogic.uploadTypes[i].type)
                        }
                    }
                    .labelsHidden()
                }
                SpaceEpicPickers(projectKey: $projectKey, epicId: $epicId)
            }
            if write || files.count <= 1 {
                SheetField(label: "Title", hint: "Optional. Defaults to the first heading, then the filename.") {
                    TextField("e.g. Ledger v2 \u{2014} Product requirements", text: $title).textFieldStyle(.roundedBorder)
                }
            }
        } footer: {
            if let error {
                Text(error).foregroundStyle(theme.swiftUIColor("pill-blocked-fg", fallback: .red)).font(.system(size: theme.pointSize(.small)))
            } else if let progress {
                Text(progress).foregroundStyle(theme.palette.tertiaryText).font(.system(size: theme.pointSize(.small)))
            }
            Spacer()
            Button("Cancel") { dismiss() }.buttonStyle(.vesper()).keyboardShortcut(.cancelAction)
            Button(write ? "Create" : files.count > 1 ? "Upload \(files.count)" : "Upload") { Task { await submit() } }
                .buttonStyle(.vesper(.primary))
                .disabled(!ready || busy)
                .keyboardShortcut(.defaultAction)
        }
        .onAppear {
            files = initialFiles
            projectKey = defaultProject
            if let first = initialFiles.first { type = LibraryLogic.guessType(name: first.lastPathComponent, mime: mimeType(first)) }
        }
    }

    private func form() -> APIMultipartForm {
        var f = APIMultipartForm()
        f.addField("project_key", projectKey)
        f.addField("type", type.rawValue)
        if !epicId.isEmpty { f.addField("epic_id", epicId) }
        return f
    }

    private func submit() async {
        guard let client = context.store.client else { return }
        busy = true
        error = nil
        defer { busy = false; progress = nil }
        let trimmedTitle = title.trimmingCharacters(in: .whitespacesAndNewlines)
        var forms: [APIMultipartForm] = []
        if write {
            var f = form()
            if !trimmedTitle.isEmpty { f.addField("title", trimmedTitle) }
            f.addField("body_md", body_)
            forms.append(f)
        } else {
            for file in files {
                var f = form()
                if !trimmedTitle.isEmpty, files.count == 1 { f.addField("title", trimmedTitle) }
                guard let data = try? Data(contentsOf: file) else {
                    error = "Couldn\u{2019}t read \(file.lastPathComponent)."
                    return
                }
                f.addFile("file", filename: file.lastPathComponent, contentType: mimeType(file), data: data)
                forms.append(f)
            }
        }
        var last: API.Artifact?
        for (index, f) in forms.enumerated() {
            if forms.count > 1 { progress = "Uploading \(index + 1) of \(forms.count)\u{2026}" }
            do {
                last = try await client.send(API.createArtifact(body: f), timeout: 120)
            } catch {
                // Finished uploads stay; the reason shows in the footer.
                self.error = (error as? APIError)?.userMessage ?? error.localizedDescription
                context.store.invalidate(QueryInvalidation(resources: ["artifacts"]))
                return
            }
        }
        context.store.invalidate(QueryInvalidation(resources: ["artifacts"]))
        dismiss()
        if let last { created(last) }
    }
}

/// New mockup: a blank wireframe or an uploaded .svg; the editor opens once it's made.
struct NewMockupSheet: View {
    @Environment(NativeScreenContext.self) private var context
    @Environment(\.vesperTheme) private var theme
    @Environment(\.dismiss) private var dismiss
    let defaultProject: String

    @State private var title = ""
    @State private var upload = false
    @State private var files: [URL] = []
    @State private var projectKey = ""
    @State private var epicId = ""
    @State private var error: String?
    @State private var busy = false

    var body: some View {
        let ready = !projectKey.isEmpty && (upload ? files.count == 1 : !title.trimmingCharacters(in: .whitespaces).isEmpty)
        SheetShell(title: "New mockup") {
            SheetField(label: "Title") {
                TextField("e.g. Payout batching \u{2014} settings screen", text: $title).textFieldStyle(.roundedBorder)
            }
            Picker("Start from", selection: $upload) {
                Text("Blank wireframe").tag(false)
                Text("Upload .svg").tag(true)
            }
            .pickerStyle(.segmented)
            .labelsHidden()
            .fixedSize()
            .onChange(of: upload) { _, on in if on, let first = files.first, title.isEmpty { title = first.deletingPathExtension().lastPathComponent } }
            if upload {
                FileList(files: $files, multiple: false, types: [.svg], hint: "One .svg file. Scripts, event handlers and external links are rejected.") { picked in
                    files = picked.filter { LibraryLogic.isSVGFile(name: $0.lastPathComponent, mime: mimeType($0)) }
                    if let first = files.first, title.trimmingCharacters(in: .whitespaces).isEmpty { title = first.deletingPathExtension().lastPathComponent }
                }
            } else {
                Text("A 1280\u{00D7}800 wireframe with a header, sidebar and content blocks. You\u{2019}ll edit the SVG source next.")
                    .foregroundStyle(theme.palette.tertiaryText)
            }
            SpaceEpicPickers(projectKey: $projectKey, epicId: $epicId)
        } footer: {
            if let error {
                Text(error).foregroundStyle(theme.swiftUIColor("pill-blocked-fg", fallback: .red)).font(.system(size: theme.pointSize(.small)))
            }
            Spacer()
            Button("Cancel") { dismiss() }.buttonStyle(.vesper()).keyboardShortcut(.cancelAction)
            Button(upload ? "Upload & edit" : "Create & edit") { Task { await submit() } }
                .buttonStyle(.vesper(.primary))
                .disabled(!ready || busy)
                .keyboardShortcut(.defaultAction)
        }
        .onAppear { projectKey = defaultProject }
    }

    private func submit() async {
        guard let client = context.store.client, !busy else { return }
        busy = true
        error = nil
        defer { busy = false }
        var f = APIMultipartForm()
        f.addField("project_key", projectKey)
        f.addField("type", "mockup")
        if !epicId.isEmpty { f.addField("epic_id", epicId) }
        let trimmed = title.trimmingCharacters(in: .whitespacesAndNewlines)
        if !trimmed.isEmpty { f.addField("title", trimmed) }
        if upload, let file = files.first {
            guard let data = try? Data(contentsOf: file) else {
                error = "Couldn\u{2019}t read \(file.lastPathComponent)."
                return
            }
            f.addFile("file", filename: file.lastPathComponent, contentType: "image/svg+xml", data: data)
        } else {
            f.addField("body_md", LibraryLogic.blankWireframe(title: title))
        }
        do {
            let artifact = try await client.send(API.createArtifact(body: f), timeout: 120)
            context.store.invalidate(QueryInvalidation(resources: ["artifacts"]))
            dismiss()
            context.navigate("/artifacts/\(artifact.id)?edit=1")
        } catch {
            self.error = (error as? APIError)?.userMessage ?? "Couldn\u{2019}t create the mockup."
        }
    }
}

/// New version: edit the markdown in place, or upload a replacement file.
struct NewVersionSheet: View {
    @Environment(NativeScreenContext.self) private var context
    @Environment(\.vesperTheme) private var theme
    @Environment(\.dismiss) private var dismiss
    let artifact: API.Artifact

    @State private var write = true
    @State private var markdown = ""
    @State private var files: [URL] = []
    @State private var label = ""
    @State private var note = ""
    @State private var error: String?
    @State private var busy = false

    private var isMockup: Bool { artifact.type == .mockup }

    var body: some View {
        let changed = write ? !markdown.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty && markdown != (artifact.bodyMd ?? "") : files.count == 1
        let next = "v\(artifact.versions.count + 1)"
        SheetShell(title: "New version of \(artifact.title)") {
            if !isMockup {
                Picker("Source", selection: $write) {
                    Text("Edit markdown").tag(true)
                    Text("Upload file").tag(false)
                }
                .pickerStyle(.segmented)
                .labelsHidden()
                .fixedSize()
            }
            if write {
                TextEditor(text: $markdown)
                    .font(.system(size: theme.pointSize(.mono), design: .monospaced))
                    .frame(height: 260)
                    .overlay(RoundedRectangle(cornerRadius: 6).stroke(theme.palette.border))
                    .accessibilityLabel("Markdown")
            } else {
                FileList(files: $files, multiple: false, types: isMockup ? [.svg] : nil,
                         hint: isMockup ? "Upload an .svg to replace the mockup. The new version needs a fresh review." : nil)
            }
            HStack(alignment: .top, spacing: 12) {
                SheetField(label: "Version label", hint: "Defaults to \(next)") {
                    TextField(next, text: $label).textFieldStyle(.roundedBorder).font(.system(size: theme.pointSize(.body), design: .monospaced))
                }
                SheetField(label: "What changed") {
                    TextField("e.g. Tightened the p95 target", text: $note).textFieldStyle(.roundedBorder)
                }
            }
        } footer: {
            if let error {
                Text(error).foregroundStyle(theme.swiftUIColor("pill-blocked-fg", fallback: .red)).font(.system(size: theme.pointSize(.small)))
            } else {
                Text("Current: \(artifact.currentVersion.label). Agents get the new version on their next read.")
                    .foregroundStyle(theme.palette.tertiaryText).font(.system(size: theme.pointSize(.small)))
            }
            Spacer()
            Button("Cancel") { dismiss() }.buttonStyle(.vesper()).keyboardShortcut(.cancelAction)
            Button("Save version") { Task { await submit() } }
                .buttonStyle(.vesper(.primary))
                .disabled(!changed || busy)
                .keyboardShortcut(.return, modifiers: write ? .command : [])
        }
        .onAppear {
            write = artifact.currentVersion.content.kind.rawValue == "markdown" && !isMockup
            markdown = artifact.bodyMd ?? ""
        }
    }

    private func submit() async {
        guard let client = context.store.client, !busy else { return }
        busy = true
        error = nil
        defer { busy = false }
        var f = APIMultipartForm()
        if !label.trimmingCharacters(in: .whitespaces).isEmpty { f.addField("version_label", label.trimmingCharacters(in: .whitespaces)) }
        if !note.trimmingCharacters(in: .whitespaces).isEmpty { f.addField("note", note.trimmingCharacters(in: .whitespaces)) }
        if write {
            f.addField("body_md", markdown)
        } else if let file = files.first {
            guard let data = try? Data(contentsOf: file) else {
                error = "Couldn\u{2019}t read \(file.lastPathComponent)."
                return
            }
            f.addFile("file", filename: file.lastPathComponent, contentType: mimeType(file), data: data)
        }
        do {
            _ = try await client.send(API.createArtifactVersion(id: artifact.id, body: f), timeout: 120)
            context.store.invalidate(QueryInvalidation(resources: ["artifacts", "knowledge"]))
            dismiss()
        } catch {
            self.error = (error as? APIError)?.userMessage ?? error.localizedDescription
        }
    }
}
