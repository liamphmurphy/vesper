/// The selected artifact beside the list: its thumbnail, metadata, outline, readers, tickets and
/// actions (web library/_components/preview.tsx).
struct ArtifactPreviewPane: View {
    @Environment(NativeScreenContext.self) private var context
    @Environment(\.vesperTheme) private var theme
    let id: String
    let close: () -> Void
    let newVersion: (API.Artifact) -> Void

    private var request: APIRequest<API.Artifact> { API.getArtifact(id: id) }

    var body: some View {
        let entry = context.store.entry(request)
        ScrollView {
            if let a = entry.data {
                loaded(a)
            } else if entry.error != nil {
                Text("Couldn\u{2019}t load this artifact.")
                    .vesperText(.body, theme)
                    .foregroundStyle(theme.swiftUIColor("pill-blocked-fg", fallback: .red))
                    .padding(20)
            } else {
                VStack(alignment: .leading, spacing: 16) {
                    SkeletonBar(height: 200)
                    SkeletonBar(height: 20).frame(width: 240)
                    SkeletonBar(height: 12)
                }
                .padding(20)
            }
        }
        .onAppear {
            context.store.load(request)
            context.store.observe(request)
        }
        .onDisappear { context.store.stopObserving(request.key) }
    }

    private func loaded(_ a: API.Artifact) -> some View {
        let content = a.currentVersion.content
        let outline = LibraryLogic.visibleOutline(a.outline)
        let markdown = content.kind.rawValue == "markdown"
        return VStack(alignment: .leading, spacing: 20) {
            HStack(spacing: 4) {
                DocTypeTag(type: a.type.rawValue)
                Spacer()
                Button { context.navigate("/artifacts/\(a.id)") } label: { Image(systemName: "link") }
                    .buttonStyle(.plain).help("Open full view").accessibilityLabel("Open full view")
                Button(action: close) { Image(systemName: "xmark") }
                    .buttonStyle(.plain).help("Close preview").accessibilityLabel("Close preview")
            }
            .foregroundStyle(theme.palette.secondaryText)
            thumbnail(a)
            VStack(alignment: .leading, spacing: 8) {
                Button { context.navigate("/artifacts/\(a.id)") } label: {
                    Text(LibraryLogic.artifactTitle(title: a.title, displayId: a.displayId)).vesperText(.title, theme).multilineTextAlignment(.leading)
                }
                .buttonStyle(.plain)
                if !a.summary.isEmpty {
                    Text(a.summary).vesperText(.body, theme).foregroundStyle(theme.palette.secondaryText)
                }
            }
            Grid(alignment: .topLeading, horizontalSpacing: 16, verticalSpacing: 12) {
                GridRow {
                    meta(a.author.type == .agent ? "Generated by" : "Owner") { Text(a.author.name) }
                    meta("Version") {
                        Text("\(a.currentVersion.label) · \(APIDate.shortAgo(a.currentVersion.createdAt))")
                            .font(.system(size: theme.pointSize(.small), design: .monospaced))
                    }
                }
                GridRow {
                    meta(markdown ? "Length" : "File") {
                        Text(markdown ? "\(a.outline.count) sections"
                             : "\(LibraryLogic.fileKind(contentType: content.contentType, filename: content.filename)) · \(LibraryLogic.formatBytes(content.sizeBytes))")
                    }
                    if let review = a.currentVersion.review {
                        meta("Review") { ReviewChip(state: review.state) }
                    } else {
                        Color.clear.gridCellUnsizedAxes([.horizontal, .vertical])
                    }
                }
                GridRow {
                    meta("Epic") {
                        if let epic = a.epic { Text(epic.name).foregroundStyle(theme.palette.accent) } else { Text("None").foregroundStyle(theme.palette.tertiaryText) }
                    }
                }
            }
            if !outline.isEmpty {
                section("Outline") {
                    ForEach(Array(outline.enumerated()), id: \.element.id) { index, s in
                        Button { context.navigate("/artifacts/\(a.id)#\(s.anchor)") } label: {
                            HStack(spacing: 12) {
                                Text("\u{00A7}\(index + 1)").font(.system(size: theme.pointSize(.small), design: .monospaced))
                                    .foregroundStyle(theme.palette.tertiaryText).frame(width: 20, alignment: .leading)
                                Text(s.heading).lineLimit(1).frame(maxWidth: .infinity, alignment: .leading)
                                Text("\(s.citations)").font(.system(size: theme.pointSize(.small), design: .monospaced))
                                    .foregroundStyle(s.citations > 0 ? theme.palette.secondaryText : theme.palette.tertiaryText)
                                    .accessibilityLabel("\(s.citations) citations")
                            }
                            .frame(height: 26)
                            .contentShape(Rectangle())
                        }
                        .buttonStyle(.plain)
                    }
                    Text("Right column: times agents cited each section")
                        .font(.system(size: theme.pointSize(.small))).foregroundStyle(theme.palette.tertiaryText)
                }
            }
            section("Read by") {
                if a.readBy.isEmpty {
                    Text("No agent has read this yet.").font(.system(size: theme.pointSize(.small))).foregroundStyle(theme.palette.tertiaryText)
                } else {
                    FlowRow(spacing: 6) {
                        ForEach(a.readBy, id: \.agent.id) { reader in
                            HStack(spacing: 6) {
                                WorkPersonaAvatarView(agent: reader.agent, size: 18)
                                Text(reader.agent.name)
                            }
                            .font(.system(size: theme.pointSize(.small)))
                            .padding(.leading, 4).padding(.trailing, 8).frame(height: 26)
                            .overlay(RoundedRectangle(cornerRadius: 4).stroke(theme.swiftUIColor("border-strong", fallback: theme.palette.border)))
                            .help("\(reader.reads) reads")
                        }
                    }
                }
            }
            if !a.tickets.isEmpty {
                section("Tickets") {
                    ForEach(a.tickets.prefix(6), id: \.key) { t in
                        Button { context.navigate("/tickets/\(t.key)") } label: {
                            HStack(spacing: 8) {
                                Text(t.key).font(.system(size: theme.pointSize(.small), design: .monospaced))
                                    .foregroundStyle(theme.palette.tertiaryText).frame(width: 64, alignment: .leading)
                                Text(t.title).lineLimit(1).frame(maxWidth: .infinity, alignment: .leading)
                                if t.relation.rawValue == "generated" {
                                    Text("generated").font(.system(size: theme.pointSize(.small) - 1))
                                        .foregroundStyle(theme.swiftUIColor("doc-report", fallback: theme.palette.secondaryText))
                                }
                            }
                            .frame(height: 28)
                            .contentShape(Rectangle())
                        }
                        .buttonStyle(.plain)
                    }
                    if a.tickets.count > 6 {
                        Text("and \(a.tickets.count - 6) more").font(.system(size: theme.pointSize(.small))).foregroundStyle(theme.palette.tertiaryText)
                    }
                }
            }
            LazyVGrid(columns: [GridItem(.flexible()), GridItem(.flexible())], spacing: 8) {
                if a.type == .mockup {
                    Button { context.navigate("/artifacts/\(a.id)?edit=1") } label: { Label("Edit", systemImage: "pencil").frame(maxWidth: .infinity) }
                        .buttonStyle(.vesper(.primary))
                }
                Button { newVersion(a) } label: { Text("New version").frame(maxWidth: .infinity) }.buttonStyle(.vesper())
                if markdown, a.type != .mockup {
                    Button { context.openInNewTab("/print/artifacts/\(a.id)") } label: { Label("Export PDF", systemImage: "printer").frame(maxWidth: .infinity) }
                        .buttonStyle(.vesper())
                }
                if a.type == .prd || a.type == .spec, let project = a.project {
                    Button { context.navigate("/plans?artifact=\(a.id)&project=\(project.key)") } label: { Text("Generate tickets").frame(maxWidth: .infinity) }
                        .buttonStyle(.vesper())
                }
            }
        }
        .vesperText(.body, theme)
        .padding(20)
    }

    @ViewBuilder
    private func thumbnail(_ a: API.Artifact) -> some View {
        let c = a.currentVersion.content
        if a.type == .mockup || (c.kind.rawValue == "file" && c.contentType.hasPrefix("image/")) {
            LibraryImageView(path: "/api/v1/artifacts/\(a.id)/versions/\(a.currentVersion.id)/content", maxPixel: 720, fill: false)
                .frame(maxWidth: .infinity, maxHeight: 200)
                .background(theme.palette.surface)
                .clipShape(RoundedRectangle(cornerRadius: 12))
                .overlay(RoundedRectangle(cornerRadius: 12).stroke(theme.palette.border))
                .accessibilityLabel("Preview of \(a.title)")
        } else {
            let sections = LibraryLogic.visibleOutline(a.outline).prefix(3)
            let track = theme.swiftUIColor("track", fallback: Color.secondary.opacity(0.15))
            VStack(alignment: .leading, spacing: 10) {
                Capsule().fill(track).frame(width: 180, height: 10)
                Capsule().fill(track).frame(width: 120, height: 6)
                ForEach(0..<(sections.isEmpty ? 2 : sections.count), id: \.self) { _ in
                    VStack(alignment: .leading, spacing: 6) {
                        Capsule().fill(theme.palette.accent.opacity(0.6)).frame(width: 100, height: 6)
                        Capsule().fill(track).frame(height: 4)
                        Capsule().fill(track).frame(width: 220, height: 4)
                    }
                    .padding(.top, 8)
                }
                Spacer(minLength: 0)
            }
            .padding(20)
            .frame(maxWidth: .infinity, minHeight: 200, maxHeight: 200, alignment: .topLeading)
            .background(theme.palette.surface)
            .clipShape(RoundedRectangle(cornerRadius: 12))
            .overlay(RoundedRectangle(cornerRadius: 12).stroke(theme.palette.border))
            .accessibilityHidden(true)
        }
    }

    private func meta<Value: View>(_ label: String, @ViewBuilder _ value: () -> Value) -> some View {
        VStack(alignment: .leading, spacing: 2) {
            Text(label).font(.system(size: theme.pointSize(.small))).foregroundStyle(theme.palette.tertiaryText)
            value()
        }
    }

    private func section<Content: View>(_ title: String, @ViewBuilder _ content: () -> Content) -> some View {
        VStack(alignment: .leading, spacing: 4) {
            Text(title).vesperText(.body, theme).foregroundStyle(theme.palette.tertiaryText)
            content()
        }
    }
}

/// Lays children out left to right, wrapping onto new rows (the web's flex-wrap).
struct FlowRow: Layout {
    var spacing: CGFloat = 6

    func sizeThatFits(proposal: ProposedViewSize, subviews: Subviews, cache: inout ()) -> CGSize {
        let width = proposal.width ?? .infinity
        var x: CGFloat = 0, y: CGFloat = 0, rowHeight: CGFloat = 0, widest: CGFloat = 0
        for view in subviews {
            let size = view.sizeThatFits(.unspecified)
            if x > 0, x + size.width > width {
                y += rowHeight + spacing
                x = 0
                rowHeight = 0
            }
            x += size.width + spacing
            rowHeight = max(rowHeight, size.height)
            widest = max(widest, x - spacing)
        }
        return CGSize(width: widest, height: y + rowHeight)
    }

    func placeSubviews(in bounds: CGRect, proposal: ProposedViewSize, subviews: Subviews, cache: inout ()) {
        var x = bounds.minX, y = bounds.minY, rowHeight: CGFloat = 0
        for view in subviews {
            let size = view.sizeThatFits(.unspecified)
            if x > bounds.minX, x + size.width > bounds.maxX {
                y += rowHeight + spacing
                x = bounds.minX
                rowHeight = 0
            }
            view.place(at: CGPoint(x: x, y: y), proposal: ProposedViewSize(size))
            x += size.width + spacing
            rowHeight = max(rowHeight, size.height)
        }
    }
}

